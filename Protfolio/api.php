<?php
/**
 * Sojol Visuals - Hostinger Live Backend API Engine
 * Handles /api/data, /api/upload, and live data persistence without requiring Python or GitHub.
 */

// Headers for CORS and JSON
header("Access-Control-Allow-Origin: *");
header("Access-Control-Allow-Methods: GET, POST, OPTIONS");
header("Access-Control-Allow-Headers: Content-Type, X-Filename, Authorization, X-Requested-With");

if ($_SERVER['REQUEST_METHOD'] === 'OPTIONS') {
    http_response_code(200);
    exit;
}

$baseDir = __DIR__;
$dataFile = $baseDir . '/portfolio_data.json';
$jsDataFile = $baseDir . '/portfolio_data.js';
$imagesDir = $baseDir . '/images';
$videosDir = $baseDir . '/videos';

if (!is_dir($imagesDir)) @mkdir($imagesDir, 0755, true);
if (!is_dir($videosDir)) @mkdir($videosDir, 0755, true);

$action = isset($_GET['action']) ? $_GET['action'] : '';

// 1. STATUS CHECK
if ($action === 'status') {
    header("Content-Type: application/json; charset=utf-8");
    echo json_encode(["online" => true, "engine" => "Hostinger PHP Server", "version" => "2.0"]);
    exit;
}

// 2. GET DATA
if ($action === 'data' && $_SERVER['REQUEST_METHOD'] === 'GET') {
    header("Content-Type: application/json; charset=utf-8");
    if (file_exists($dataFile)) {
        readfile($dataFile);
    } else {
        echo "{}";
    }
    exit;
}

// 3. POST SAVE DATA
if ($action === 'data' && $_SERVER['REQUEST_METHOD'] === 'POST') {
    header("Content-Type: application/json; charset=utf-8");
    $rawInput = file_get_contents("php://input");
    if (!$rawInput) {
        http_response_code(400);
        echo json_encode(["success" => false, "error" => "Empty payload"]);
        exit;
    }

    $decoded = json_decode($rawInput, true);
    if (!is_array($decoded)) {
        http_response_code(400);
        echo json_encode(["success" => false, "error" => "Invalid JSON"]);
        exit;
    }

    // Save to portfolio_data.json
    file_put_contents($dataFile, json_encode($decoded, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));

    // Also update portfolio_data.js for instant fallback sync
    $jsData = "// Auto-generated by Sojol Admin Engine\nwindow.PORTFOLIO_DATA = " . json_encode($decoded, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE) . ";\n";
    file_put_contents($jsDataFile, $jsData);

    echo json_encode(["success" => true, "message" => "Saved securely to Hostinger server!"]);
    exit;
}

// 4. POST UPLOAD (VIDEO OR IMAGE)
if ($action === 'upload' && $_SERVER['REQUEST_METHOD'] === 'POST') {
    header("Content-Type: application/json; charset=utf-8");
    $targetDir = $imagesDir;
    $relPrefix = "images/";
    
    // Check if filename indicates video
    $rawFilename = isset($_SERVER['HTTP_X_FILENAME']) ? rawurldecode($_SERVER['HTTP_X_FILENAME']) : (isset($_GET['filename']) ? $_GET['filename'] : '');
    $ext = strtolower(pathinfo($rawFilename, PATHINFO_EXTENSION));
    $videoExts = ['mp4', 'webm', 'mov', 'm4v', 'mkv', 'avi', 'ogv'];
    
    if (in_array($ext, $videoExts) || (isset($_GET['type']) && $_GET['type'] === 'video')) {
        $targetDir = $videosDir;
        $relPrefix = "videos/";
        if (!$ext) $ext = 'mp4';
    } else {
        if (!$ext) $ext = 'png';
    }

    $uniqueName = 'upload_' . uniqid() . '.' . $ext;
    $targetPath = $targetDir . '/' . $uniqueName;

    // Handle multipart form upload
    if (isset($_FILES['file']) && $_FILES['file']['error'] === UPLOAD_ERR_OK) {
        if (move_uploaded_file($_FILES['file']['tmp_name'], $targetPath)) {
            echo json_encode(["success" => true, "url" => $relPrefix . $uniqueName]);
            exit;
        }
    }

    // Handle direct binary stream or Base64 JSON
    $rawInput = file_get_contents("php://input");
    if ($rawInput) {
        $json = json_decode($rawInput, true);
        if (is_array($json) && !empty($json['data'])) {
            $dataStr = $json['data'];
            if (preg_match('/^data:([^;]+);base64,(.+)$/', $dataStr, $matches)) {
                file_put_contents($targetPath, base64_decode($matches[2]));
                echo json_encode(["success" => true, "url" => $relPrefix . $uniqueName]);
                exit;
            }
        }
        // Direct stream
        file_put_contents($targetPath, $rawInput);
        echo json_encode(["success" => true, "url" => $relPrefix . $uniqueName]);
        exit;
    }

    http_response_code(400);
    echo json_encode(["success" => false, "error" => "No file uploaded"]);
    exit;
}

// Fallback
http_response_code(404);
echo json_encode(["error" => "Invalid API endpoint"]);
